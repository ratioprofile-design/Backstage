/**
 * Translates a given English text to Tamil if the application language is Tamil.
 * Returns the original English string if appLanguage is not 'tamil' or if no translation exists.
 */
export function translateUi(text: string, appLanguage?: string): string {
  if (appLanguage !== 'tamil') return text;
  if (!text) return '';
  const trimmed = text.trim();
  if (TAMIL_UI_DICTIONARY[trimmed]) {
    return TAMIL_UI_DICTIONARY[trimmed];
  }
  return text;
}
